"""Business-logic scenario traceability gate.

Checks that every OpenSpec change declares at least one scenario and that each
change is mapped to existing backend tests and API cases. Scenario semantics and
state transitions still require the documented AI/human review; this gate only
proves the mapping is present and its targets exist.

Exit: 0 all mapped; 1 missing spec/scenario/mapping/target.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHANGES_DIR = ROOT / "openspec" / "changes"
CASES_DIR = ROOT / "apitest" / "cases"
TESTS_DIR = ROOT / "backend" / "tests"
REPORT = ROOT / "reports" / "scenario-coverage.md"

MAPPING = {
    "01-literature-management": {
        "backend": ["test_auth.py", "test_documents.py", "test_library.py"],
        "api": ["auth-*.ps1", "docs-*.ps1"],
    },
    "02-pdf-reader": {
        "backend": ["test_annotations.py", "test_reader_assets.py", "test_reader_progress.py",
                    "test_pdf_exports.py", "test_pdf_text.py"],
        "api": ["anno-*.ps1", "docs-progress.ps1", "docs-file-download.ps1"],
    },
    "03-translation": {
        "backend": ["test_translations.py", "test_translation_runtime.py", "test_model_secrets.py"],
        "api": ["trans-*.ps1"],
    },
    "04-literature-notes": {
        "backend": ["test_notes.py", "test_note_captures.py", "test_note_search.py",
                    "test_note_titles.py", "test_ai_note_captures.py"],
        "api": ["notes-*.ps1"],
    },
    "05-metadata-extraction": {
        "backend": ["test_metadata_extraction_async.py"],
        "api": ["extr-*.ps1"],
    },
    "06-ai-qa": {
        "backend": ["test_qa_api.py", "test_qa_rag.py"],
        "api": ["qa-*.ps1"],
    },
    "07-user-model-settings": {
        "backend": ["test_user_models.py", "test_user_model_preview.py"],
        "api": ["trans-model-settings.ps1"],
    },
}

SCENARIO = re.compile(r"^####\s+Scenario:\s*(.+?)\s*$", re.MULTILINE)


def main() -> int:
    changes = sorted(path for path in CHANGES_DIR.iterdir()
                     if path.is_dir() and path.name not in {"archive"})
    failures: list[str] = []
    rows: list[tuple[str, int, str, str]] = []

    for change in changes:
        specs = sorted((change / "specs").glob("*/spec.md"))
        scenarios = []
        for spec in specs:
            scenarios.extend(SCENARIO.findall(spec.read_text(encoding="utf-8")))
        if not specs:
            failures.append(f"{change.name}: no specs/*/spec.md")
        if not scenarios:
            failures.append(f"{change.name}: no '#### Scenario:' entries")

        targets = MAPPING.get(change.name)
        if not targets:
            failures.append(f"{change.name}: no test mapping in scripts/check_scenarios.py")
            rows.append((change.name, len(scenarios), "-", "-"))
            continue

        missing = [name for name in targets["backend"] if not (TESTS_DIR / name).is_file()]
        api_matches = []
        for pattern in targets["api"]:
            matched = sorted(path.name for path in CASES_DIR.glob(pattern))
            if not matched:
                missing.append(f"apitest/cases/{pattern}")
            api_matches.extend(matched)
        failures.extend(f"{change.name}: missing target {name}" for name in missing)

        backend_list = ", ".join(targets["backend"])
        api_list = ", ".join(sorted(set(api_matches)))
        rows.append((change.name, len(scenarios), backend_list, api_list))

    lines = [
        "# Scenario traceability (generated by scripts/check_scenarios.py)",
        "",
        "This gate proves each change has scenarios and existing test targets.",
        "It does not prove scenario semantics: state-transition review stays manual/AI-reviewed.",
        "",
        "| Change | Scenarios | Backend tests | API cases |",
        "| --- | --- | --- | --- |",
    ]
    for name, count, backend, api in rows:
        lines.append(f"| {name} | {count} | {backend} | {api} |")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"scenario report: {REPORT}")
    print(f"changes={len(changes)} scenarios={sum(row[1] for row in rows)} failures={len(failures)}")
    for failure in failures:
        print(f"FAIL {failure}")
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
