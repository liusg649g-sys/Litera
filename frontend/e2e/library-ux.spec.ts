import { test, expect } from '@playwright/test'
import type { APIRequestContext, Page } from '@playwright/test'
import { pdf, session, upload, openLibrary, origin, selectLibraryOption, setLibraryCheckbox } from './library-fixtures'
const headers = (token: string) => ({ Origin: origin, 'X-CSRF-Token': token })
async function category(request: APIRequestContext, token: string, kind: string, name: string) {
  const response = await request.post('/api/v1/' + kind, { headers: headers(token), data: { name } })
  expect(response.status()).toBe(201); return response.json()
}
async function menu(page: Page, name: string) {
  await page.getByRole('button', { name: /更多操作/ }).first().click()
  await page.getByRole('menuitem', { name, exact: true }).click()
}

test('quick classification saves only its fields, cancels without writes, syncs panel and handles real conflict', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  const token = await session(page.request)
  const folder = await category(page.request, token, 'folders', '快捷目标')
  const a = await category(page.request, token, 'tags', '原有标签'), b = await category(page.request, token, 'tags', '新标签')
  const doc = await (await upload(page.request, token, pdf('quick'), '快捷文献.pdf')).json()
  await page.request.patch('/api/v1/documents/' + doc.id, { headers: headers(token), data: { version: 1, tagIds: [a.id], year: 2026 } })
  await page.goto('/library')
  await page.getByRole('button', { name: '详情', exact: true }).click()
  await expect(page.getByRole('heading', { name: '快捷文献', exact: true })).toBeVisible()
  const updates: object[] = []
  page.on('request', request => { if (request.method() === 'PATCH' && request.url().endsWith('/documents/' + doc.id)) updates.push(request.postDataJSON()) })
  await menu(page, '移动到文件夹')
  await expect(page.getByRole('dialog')).toContainText('当前所属文件夹：未分类')
  await expect(page.locator('.metadata-form')).not.toBeVisible()
  await selectLibraryOption(page, '目标文件夹', folder.name)
  expect(await page.locator('.library-select-menu .el-select-dropdown__item').filter({ hasText: folder.name }).last().evaluate(element => !!element.closest('.el-dialog'))).toBe(false)
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
  expect(updates).toHaveLength(0)
  expect((await (await page.request.get('/api/v1/documents/' + doc.id)).json()).folderId).toBeNull()
  await menu(page, '移动到文件夹')
  await selectLibraryOption(page, '目标文件夹', folder.name)
  await page.getByRole('dialog').getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.locator('.document-info-panel')).toContainText(folder.name)
  expect(updates[0]).toEqual({ version: 2, folderId: folder.id })
  await menu(page, '管理标签')
  await expect(page.getByRole('dialog').getByRole('checkbox', { name: a.name, exact: true })).toBeChecked()
  await setLibraryCheckbox(page, b.name)
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
  expect(updates).toHaveLength(1)
  await menu(page, '管理标签')
  await expect(page.getByRole('dialog').getByRole('checkbox', { name: b.name, exact: true })).not.toBeChecked()
  await setLibraryCheckbox(page, b.name)
  await page.request.patch('/api/v1/documents/' + doc.id, { headers: headers(token), data: { version: 3, title: '并发新标题' } })
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('文献已被更新')
  await expect(page.getByRole('dialog').getByRole('checkbox', { name: b.name, exact: true })).toBeChecked()
  await page.getByRole('button', { name: '载入最新版本并保留选择' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('.document-info-panel')).toContainText('原有标签、新标签')
  await expect(page.getByRole('heading', { name: '并发新标题', exact: true })).toBeVisible()
  const saved = await (await page.request.get('/api/v1/documents/' + doc.id)).json()
  expect(saved.tags.map((tag: { id: string }) => tag.id).sort()).toEqual([a.id, b.id].sort())
  expect(saved.year).toBe(2026)
  expect(Object.keys(updates.at(-1)!)).toEqual(['version', 'tagIds'])
  await page.getByRole('button', { name: '编辑题录', exact: true }).click()
  await expect(page.locator('.metadata-form fieldset')).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: '文献所属文件夹', exact: true })).toBeVisible()
  const checkbox = page.locator('.metadata-form .el-checkbox').first()
  expect(await checkbox.evaluate(element => getComputedStyle(element).flexDirection)).toBe('row')
  await selectLibraryOption(page, '文献所属文件夹', '未分类')
  await setLibraryCheckbox(page, a.name, false)
  await page.getByLabel('标题', { exact: true }).fill('完整编辑继续可用')
  await page.getByRole('button', { name: '保存题录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '完整编辑继续可用', exact: true })).toBeVisible()
  const full = await (await page.request.get('/api/v1/documents/' + doc.id)).json()
  expect(full.folderId).toBeNull(); expect(full.tags.map((tag: { id: string }) => tag.id)).toEqual([b.id])
})

test('debounced live query resets page, cancels old response and preserves other filters when cleared', async ({ page }) => {
  const token = await session(page.request)
  const folder = await category(page.request, token, 'folders', '即时检索'), tag = await category(page.request, token, 'tags', '共同标签')
  for (let i = 0; i < 22; i++) {
    const doc = await (await upload(page.request, token, pdf('live' + i), (i === 21 ? 'Beta唯一' : 'Alpha' + i) + '.pdf')).json()
    expect((await page.request.patch('/api/v1/documents/' + doc.id, { headers: headers(token), data: { version: 1, folderId: folder.id, tagIds: [tag.id], year: 2026 } })).status()).toBe(200)
  }
  await page.goto('/library?view=search')
  await selectLibraryOption(page, '筛选文件夹', folder.name)
  await page.getByRole('button', { name: '标签筛选', exact: true }).click()
  await page.getByRole('checkbox', { name: tag.name, exact: true }).check()
  await page.getByRole('heading', { name: '文献检索', exact: true }).click()
  await page.getByLabel('起始年份').fill('2026'); await page.getByLabel('结束年份').fill('2026')
  await selectLibraryOption(page, '排序字段', '标题'); await selectLibraryOption(page, '排序方向', '升序')
  await page.getByRole('button', { name: '检索', exact: true }).click()
  await expect(page.getByText('共 22 篇', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Go to next page', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(2)
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/v1/documents?*', async route => {
    if (new URL(route.request().url()).searchParams.get('q') !== 'Alpha') { await route.continue(); return }
    const actual = await route.fetch(); await gate
    await route.fulfill({ response: actual }).catch(() => {})
  })
  const searches: URL[] = []
  page.on('request', request => { if (request.url().includes('/api/v1/documents?') && new URL(request.url()).searchParams.has('q')) searches.push(new URL(request.url())) })
  await page.getByLabel('检索关键词').fill('A'); await page.getByLabel('检索关键词').fill('Al'); await page.getByLabel('检索关键词').fill('Alpha')
  await page.clock.runFor(299)
  expect(searches).toHaveLength(0)
  await page.clock.runFor(1)
  await expect.poll(() => searches.length).toBe(1)
  expect(searches[0].searchParams.get('page')).toBe('1')
  expect(searches[0].searchParams.get('folderId')).toBe(folder.id)
  expect(searches[0].searchParams.get('tagIds')).toBe(tag.id)
  expect(searches[0].searchParams.get('yearFrom')).toBe('2026')
  expect(searches[0].searchParams.get('sort')).toBe('title')
  expect(searches[0].searchParams.get('order')).toBe('asc')
  await expect(page.locator('tbody tr')).toHaveCount(2)
  await expect(page.getByText('正在检索…', { exact: true })).toBeVisible()
  await page.getByLabel('检索关键词').fill('Beta')
  await page.clock.runFor(300)
  await expect(page.getByRole('button', { name: 'Beta唯一', exact: true })).toBeVisible()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  release()
  await page.clock.runFor(400)
  await expect(page.getByRole('button', { name: 'Beta唯一', exact: true })).toBeVisible()
  await page.getByLabel('检索关键词').fill('')
  await page.clock.runFor(300)
  await expect(page.getByText('共 22 篇', { exact: true })).toBeVisible()
  await expect(page.locator('tbody tr')).toHaveCount(20)
  await expect(page.getByLabel('起始年份')).toHaveValue('2026')
  await expect(page.getByRole('button', { name: '标签筛选 (1)', exact: true })).toBeVisible()
})

