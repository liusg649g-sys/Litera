test('panel tags are single-line vertical rows with overflow tooltip, local scroll and unchanged save/cancel', async ({ page }) => {
  const token = await session(page.request), longName = 'label_1_' + 'long_tag_name_'.repeat(6)
  const longTag = await category(page.request, token, 'tags', longName)
  for (let i = 0; i < 9; i++) await category(page.request, token, 'tags', 'label_' + (i + 2))
  const doc = await (await upload(page.request, token, pdf('panel-tag-list'))).json()
  await page.request.patch('/api/v1/documents/' + doc.id, { headers: headers(token), data: { version: 1, tagIds: [longTag.id] } })
  await page.setViewportSize({ width: 1920, height: 1080 }); await page.goto('/library')
  await menu(page, '编辑题录信息')
  const list = page.locator('.panel-tag-list')
  await expect(list.getByRole('checkbox')).toHaveCount(10)
  expect(await list.evaluate(element => ({ scrolls: element.scrollHeight > element.clientHeight, height: element.clientHeight }))).toEqual({ scrolls: true, height: 200 })
  const dimensions = await list.locator('.el-checkbox').evaluateAll(elements => elements.map(element => {
    const bounds = element.getBoundingClientRect(), icon = element.querySelector('.el-checkbox__input')!.getBoundingClientRect(), text = element.querySelector('.cell-text')!.getBoundingClientRect()
    return { x: bounds.x, height: bounds.height, aligned: Math.abs(icon.y + icon.height / 2 - text.y - text.height / 2) < 2, right: text.x > icon.x + icon.width }
  }))
  expect(dimensions.every(item => item.height === 32 && item.x === dimensions[0].x && item.aligned && item.right)).toBe(true)
  const longLabel = list.locator('.el-checkbox').filter({ has: page.getByRole('checkbox', { name: longName, exact: true }) })
  await longLabel.scrollIntoViewIfNeeded()
  const text = longLabel.locator('.cell-text')
  expect(await text.evaluate(element => ({ overflow: element.scrollWidth > element.clientWidth, whitespace: getComputedStyle(element).whiteSpace, ellipsis: getComputedStyle(element).textOverflow }))).toEqual({ overflow: true, whitespace: 'nowrap', ellipsis: 'ellipsis' })
  await text.hover()
  await expect(page.getByRole('tooltip', { name: longName, exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: longName, exact: true })).toBeChecked()
  await page.getByRole('button', { name: '取消编辑', exact: true }).click()
  expect((await (await page.request.get('/api/v1/documents/' + doc.id)).json()).version).toBe(2)
  await page.getByRole('button', { name: '编辑题录', exact: true }).click()
  await setLibraryCheckbox(page, 'label_2')
  await page.getByRole('button', { name: '取消编辑', exact: true }).click()
  await page.getByRole('button', { name: '放弃修改', exact: true }).click()
  expect((await (await page.request.get('/api/v1/documents/' + doc.id)).json()).tags.map((tag: { id: string }) => tag.id)).toEqual([longTag.id])
  await page.getByRole('button', { name: '编辑题录', exact: true }).click()
  await setLibraryCheckbox(page, 'label_2')
  await page.getByRole('button', { name: '保存题录', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑题录', exact: true })).toBeVisible()
  expect((await (await page.request.get('/api/v1/documents/' + doc.id)).json()).tags).toHaveLength(2)
  await page.setViewportSize({ width: 360, height: 560 })
  await page.getByRole('button', { name: '编辑题录', exact: true }).click()
  await list.scrollIntoViewIfNeeded()
  expect(await list.evaluate(element => element.clientHeight <= 200 && element.scrollHeight > element.clientHeight)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/panel-tags-vertical-mobile.png', fullPage: true })
})
