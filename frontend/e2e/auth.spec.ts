import { test, expect } from '@playwright/test'
test('real registration, duplicate, login, refresh, profile, logout and route guard', async ({ page }) => {
  const email = 'e2e-' + Date.now() + '@example.com'
  await page.goto('/library')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByRole('link', { name: '注册', exact: true }).click()
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  await expect(page.getByText('请输入邮箱')).toBeVisible()
  await page.getByLabel('显示名称', { exact: true }).fill('测试研究者')
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill('Litera-test-123')
  await page.getByLabel('确认密码', { exact: true }).fill('different')
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  await expect(page.getByText('两次密码输入不一致')).toBeVisible()
  await page.getByLabel('确认密码', { exact: true }).fill('Litera-test-123')
  await page.screenshot({ path: 'test-results/register-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  await expect(page.getByText('注册成功，请使用你的邮箱和密码登录')).toBeVisible()
  await page.getByRole('link', { name: '注册', exact: true }).click()
  await page.getByLabel('显示名称', { exact: true }).fill('重复用户')
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill('Litera-test-123')
  await page.getByLabel('确认密码', { exact: true }).fill('Litera-test-123')
  await page.screenshot({ path: 'test-results/register-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  await expect(page.getByText('该邮箱已注册，请直接登录')).toBeVisible()
  await page.getByRole('link', { name: '登录', exact: true }).click()
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByText('邮箱或密码不正确')).toBeVisible()
  await page.getByLabel('密码', { exact: true }).fill('Litera-test-123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/library$/)
  await expect(page.getByRole('heading', { name: '我的文献', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('测试研究者', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.length)).toBe(0)
  const cookie = (await page.context().cookies()).find(cookie => cookie.name === 'litera_session')
  expect(cookie?.httpOnly).toBe(true)
  await page.getByRole('link', { name: '个人资料', exact: true }).click()
  await page.getByLabel('显示名称', { exact: true }).fill('更新后的研究者')
  await page.getByRole('button', { name: '保存资料' }).click()
  await expect(page.getByText('资料已保存')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('显示名称', { exact: true })).toHaveValue('更新后的研究者')
  await page.getByRole('link', { name: '返回文献库' }).click()
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/library')
  await expect(page).toHaveURL(/\/login$/)
})

test('mobile layout and service failure are explicit', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/login')
  await expect(page.getByRole('heading', { name: '欢迎回到 Litera' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/login-mobile.png', fullPage: true })
  await page.route('**/api/v1/auth/login', route => route.abort())
  await page.getByLabel('邮箱', { exact: true }).fill('offline@example.com')
  await page.getByLabel('密码', { exact: true }).fill('Litera-test-123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByText('无法连接服务，请检查网络后重试')).toBeVisible()
})

