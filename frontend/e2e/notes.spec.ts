import {test,expect,type Page} from '@playwright/test'
import {openLibrary,upload,origin} from './library-fixtures'
import {readerPdf} from './reader-fixtures'

type Doc={id:string;title:string}
async function setup(page:Page,count=1){
 const token=await openLibrary(page),docs:Doc[]=[]
 const account=await(await page.request.get('/api/v1/auth/session')).json()
 for(let index=0;index<count;index++)docs.push(await(await upload(page.request,token,readerPdf('Notes public fixture '+index,3),`Notes fixture ${index}.pdf`)).json())
 await open(page,docs[0]!)
 return {token,docs,email:account.user.email}
}
async function open(page:Page,doc:Doc){
 await page.goto(`/reader/${doc.id}`)
 await expect(page.locator('.pdf-page[data-page="1"]')).toHaveAttribute('data-status','已渲染')
 await page.getByRole('button',{name:'笔记面板',exact:true}).click()
 await expect(page.getByRole('button',{name:'新建笔记',exact:true})).toBeEnabled()
}
async function create(page:Page,title:string,content:string){
 const created=page.waitForResponse(response=>response.request().method()==='POST' && response.url().endsWith('/api/v1/notes'))
 await page.getByRole('button',{name:'新建笔记',exact:true}).click()
 const response=await created;expect(response.status()).toBe(201)
 const note=await response.json()
 await page.getByLabel('笔记标题',{exact:true}).fill(title)
 await page.getByLabel('笔记正文',{exact:true}).fill(content)
 await saved(page,note.id,content,title)
 return note.id as string
}
async function saved(page:Page,id:string,content:string,title?:string){
 await expect.poll(async()=>{const response=await page.request.get(`/api/v1/notes/${id}`);if(response.status()!==200)return null;const note=await response.json();return {content:note.content,title:note.title}},{timeout:10000}).toMatchObject({content,...(title?{title}:{})})
 await expect(page.getByTestId('note-save-status')).toHaveText('已保存')
}
async function choose(page:Page,title:string){await page.getByRole('button',{name:'打开笔记：'+title,exact:true}).click();await expect(page.getByLabel('笔记标题',{exact:true})).toHaveValue(title)}

