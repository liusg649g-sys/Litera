test('C1 real snapshot download, original bytes, saved comment body and independent PDF.js load',async({page},info)=>{
  const {doc,bytes,token}=await setup(page,'基于双目视觉的水下场景三维重建.pdf')
  await button(page,'下载 PDF').click()
  await expect(page.getByRole('menuitem',{name:'导出带批注 PDF',exact:true})).toContainText('包含当前已保存的批注')
  await expect(page.getByRole('menuitem',{name:'下载原始 PDF',exact:true})).toContainText('保留上传时的原始文件')
  await expect(page.getByRole('menuitem',{name:'下载原始 PDF',exact:true})).toBeVisible()
  await page.screenshot({path:info.outputPath('c1-download-menu.png'),animations:'disabled'})
  const originalDownload=page.waitForEvent('download')
  await page.getByRole('menuitem',{name:'下载原始 PDF',exact:true}).click()
  const original=await originalDownload
  expect(original.suggestedFilename()).toBe('基于双目视觉的水下场景三维重建.pdf')
  expect(await readFile((await original.path())!)).toEqual(bytes)
  await draft(page,'中文导出正文 αβ ±∞ →\n第二行 English')
  await button(page,'保存批注').click();await expect(page.getByLabel('批注正文',{exact:true})).toHaveCount(0)
  const downloaded=page.waitForEvent('download');await exportMenu(page);const download=await downloaded
  expect(download.suggestedFilename()).toBe('基于双目视觉的水下场景三维重建_带批注.pdf');const file=(await download.path())!,body=await readFile(file)
  expect(body.subarray(0,4).toString()).toBe('%PDF')
  expect(await(await page.request.get(`/api/v1/documents/${doc.id}/content`)).body()).toEqual(bytes)
  await expect(page.locator('.pdf-export-status:visible')).toContainText('已生成')
  const toast=page.locator('.pdf-export-status:visible')
  await expect(toast).toHaveCSS('position','fixed')
  const box=(await toast.boundingBox())!,viewport=page.viewportSize()!
  expect(Math.abs(box.x+box.width/2-viewport.width/2)).toBeLessThan(2)
  expect(box.y).toBe(16)
  await page.screenshot({path:info.outputPath('c1-export-success.png')})
  await expect(toast).toHaveCount(0,{timeout:5000})
  // Re-upload generated bytes as a separate document and parse with production PDF.js.
  const reopened=await(await upload(page.request,token,body,'exported.pdf')).json()
  await page.goto(`/reader/${reopened.id}`);await rendered(page)
  await expect(page.locator('.reader-paging')).toContainText('/ 4')
  const native=page.locator('.pdf-page[data-page="1"] [data-native-comment]').first()
  await expect(native).toHaveAttribute('aria-label',/中文导出正文/)
  await native.hover();await expect(page.locator('.pdf-comment-popup:visible')).toContainText('中文导出正文')
  await expect(page.locator('.pdf-comment-popup:visible')).toContainText('第二行 English')
  await page.mouse.move(30,30);await expect(page.locator('.pdf-comment-popup:visible')).toHaveCount(0)
  await native.click();await page.mouse.move(30,30)
  await expect(page.locator('.pdf-comment-popup:visible')).toContainText('中文导出正文')
  await page.getByLabel('PDF 阅读区域',{exact:true}).click({position:{x:20,y:20}})
  await expect(page.locator('.pdf-comment-popup:visible')).toHaveCount(0)
})

