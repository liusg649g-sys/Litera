test('C1 failure retry, duplicate guard, cancellation and reading stays usable',async({page})=>{
  await setup(page)
  await page.route('**/annotated-pdf',route=>route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({error:{code:'ANNOTATION_REVISION_CONFLICT',message:'已保存批注版本已变化'}})}))
  await exportMenu(page);await expect(page.locator('.pdf-export-status:visible')).toContainText('版本已变化')
  await page.unroute('**/annotated-pdf')
  const downloaded=page.waitForEvent('download');await button(page,'重试导出').click();await downloaded
  let requests=0
  await page.route('**/annotated-pdf',async route=>{requests++;await new Promise(r=>setTimeout(r,1800));await route.abort().catch(()=>{})})
  await exportMenu(page);await expect(page.locator('.pdf-export-status:visible')).toContainText('正在导出')
  await button(page,'下载 PDF').click();await expect(page.getByRole('menuitem',{name:'导出带批注 PDF',exact:true})).toHaveAttribute('aria-disabled','true');await page.keyboard.press('Escape')
  await button(page,'下一页').click();await expect(page.getByLabel('当前页码',{exact:true})).toHaveValue('2')
  await button(page,'取消导出').click();await expect(page.locator('.pdf-export-status:visible')).toHaveCount(0);expect(requests).toBe(1)
})

